"""Build an evidence report from saved runs only; never executes an evaluation."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build_report(runs_dir: Path) -> str:
    runs = [(p, json.loads(p.read_text(encoding="utf-8"))) for p in sorted(runs_dir.glob("*.json"))]
    latest = {}
    for p, run in sorted(runs, key=lambda pair: (pair[1].get("meta", {}).get("run_id", pair[0].stem), pair[0].name)):
        workflow = p.name.split("-")[0]
        if workflow in ("w1", "w2") and run.get("meta", {}).get("mode") != "rules":
            latest[workflow] = (p, run)
    lines = ["# Evaluation report", "", "Generated by `tools/build_eval_report.py` from saved JSON; no eval or model call.", "",
             "## Headline (latest graph runs)", "", "| Workflow | Run | Model | p95 (s) | Metrics |", "|---|---|---|---|---|"]
    for workflow, (p, r) in sorted(latest.items()):
        m = r["metrics"]
        keys = ("red_flag_recall", "specialty_accuracy") if workflow == "w1" else ("content_hit", "verified_rate", "scope_leaks")
        lines.append(f"| {workflow.upper()} | {r['meta']['run_id']} | {r['meta'].get('model', 'not recorded')} | {m.get('latency_p95_s', 'not measured')} | " + "; ".join(f"{k}={m.get(k, 'not measured')}" for k in keys) + " |")
    lines += ["", "## Page 16 targets", "", "| Target | Measured (run id) | Met | Evidence | Gap / measurement tier and day |", "|---|---|---|---|---|"]

    def measured(label, workflow, key, predicate):
        pair = latest.get(workflow)
        value = pair[1]["metrics"].get(key) if pair else None
        lines.append(f"| {label} | {value if value is not None else 'not measured'}" +
                     (f" ({pair[1]['meta']['run_id']})" if pair and value is not None else "") +
                     f" | {'yes' if value is not None and predicate(value) else 'NO'} | " +
                     (f"evals/runs/{pair[0].name}" if pair else "No saved run") +
                     " | Synthetic set only; not a production guarantee |")

    def gap(label, evidence, reason, status="NO"):
        lines.append(f"| {label} | not measured | {status} | {evidence} | {reason} |")

    measured("Triage turn p95 < 4 s", "w1", "latency_p95_s", lambda x: x < 4)
    measured("Record answer p95 < 8 s", "w2", "latency_p95_s", lambda x: x < 8)
    gap("Note draft p95 < 20 s", "docs/diagrams/w3-graph.md", "W3 is Pro; measure on W3 delivery day (unscheduled)")
    measured("Red-flag recall 100%", "w1", "red_flag_recall", lambda x: x == 1)
    measured("Specialty accuracy >= 85%", "w1", "specialty_accuracy", lambda x: x >= .85)
    gap("Answer faithfulness >= 0.9, calibrated judge", "Latest W2 headline proxies: content_hit and verified_rate", "Pro calibrated judge on W2 hardening day (unscheduled); proxies do not measure faithfulness")
    measured("Scope leaks 0 on red-team set", "w2", "scope_leaks", lambda x: x == 0)
    gap("Bookings completed without a call >= 70% of synthetic sessions", "services/agent/tests/test_w1_graph.py::test_routine_case_pauses_for_the_pick_then_books_on_resume", "Triage runs stop before booking; Core demo/day-8 end-to-end session measurement pending")
    gap("Time to book median < 3 min", "Same booking test; no session timing run", "Core demo/day-8 timed synthetic sessions pending")
    gap("Availability 99.5% in clinic hours", "infra/docker-compose.yml", "Not measured; Architect clinic-hours observation day (unscheduled)")
    gap("Audit: every record read logged with actor, purpose, time", "services/records/tests/test_w2.py::test_answer_is_cited_verified_and_audited; infra/db/tests/test_schema.py::test_audit_is_append_only_and_answers_who_saw; services/agent/w2/tools.py; infra/db/001_schema.sql", "Core application read auditing exists; tests cover answer reads/actor and append-only schema, not exhaustive SQL read coverage. Architect access-path audit day (unscheduled)", "partial")
    gap("Doctor review time per note < 90 s", "docs/diagrams/w3-graph.md", "W3 is Pro; timed doctor study on W3 validation day (unscheduled)")
    gap("Cost per consultation computed with p.34 formula", "Saved run tokens; cost section below", "Measured call/turn token averages only; full consultation workflow mix and prices pending Core demo/day-8", "partial")
    gap("Residency: identified text stays in-region", "services/agent/w1/guards.py; infra/deployment-adr.md", "Regex egress guard exists; hosting region and complete de-identification unverified. Architect deployment day (unscheduled)", "partial")
    gap("Retention: audio gone within 24 h; audit kept 1 year", "infra/db/001_schema.sql", "Append-only audit exists; no timed retention proof. Pro W3 audio lifecycle; Architect audit retention validation day (unscheduled)")
    gap("Recovery: restore within 4 h", "infra/docker-compose.yml", "Not measured; Architect timed backup/restore drill day (unscheduled)")
    gap("Recovery: checkpoints survive restarts", "services/agent/w1/cli.py (--resume); services/agent/tests/test_w1_graph.py::test_resume_after_restart_uses_the_checkpoint; services/api/tests/test_api_postgres.py::test_postgres_pick_slot_resume_and_replay", "W1 Postgres resume path exists; graph test recompiles against shared saver, not a process crash. W2 lacks durable checkpointer. Architect crash drill day (unscheduled)", "partial")
    lines += ["", "## Every saved run (variance)", "", "| File | Run id | Model | Prompt / rules version | p95 (s) |", "|---|---|---|---|---|"]
    for p, r in runs:
        meta, m = r.get("meta", {}), r.get("metrics", {})
        lines.append(f"| evals/runs/{p.name} | {meta.get('run_id', 'not recorded')} | {meta.get('model', 'not recorded')} | {meta.get('prompt_version', 'not recorded')} / {meta.get('rules_version', 'not recorded')} | {m.get('latency_p95_s', 'not measured')} |")
    lines += ["", "## Cost (p.34)", "", "C_consult = sum over workflow calls ((input_tokens × PRICE_IN_PER_MTOK + output_tokens × PRICE_OUT_PER_MTOK) / 1,000,000). Add local embedding, hosting, storage and other non-LLM costs separately. Multiply each workflow's measured per-call cost by its calls per consultation; that consultation mix is not measured here.", "", "Prices are optional shell environment values; this script never loads dotenv.", "", f"Price list date: {os.environ.get('PRICE_DATE') or 'to fill'}", "", "| Workflow / run | Calls | Input/output tokens per call | Input/output tokens per evaluated turn or answer | LLM cost per call / evaluated unit |", "|---|---|---|---|---|"]
    for w, (p, r) in sorted(latest.items()):
        t = r.get("meta", {}).get("tokens", {})
        calls = t.get("calls", 0)
        # W1 unit = each evaluated triage case; W2 = emitted answer routes.
        units = r["metrics"].get("cases", 0) if w == "w1" else sum(x.get("route") == "answer" for x in r.get("predictions", []))
        if not calls or not units or "prompt" not in t or "completion" not in t:
            lines.append(f"| {w} / {r['meta']['run_id']} | {calls} | not measured | not measured | token totals or denominator unavailable |")
            continue
        pin, pout = t["prompt"], t["completion"]
        cost = "formula above; prices to fill"
        if os.environ.get("PRICE_IN_PER_MTOK") and os.environ.get("PRICE_OUT_PER_MTOK"):
            total = (pin * float(os.environ["PRICE_IN_PER_MTOK"]) + pout * float(os.environ["PRICE_OUT_PER_MTOK"])) / 1_000_000
            cost = f"{total/calls:.8f} / {total/units:.8f} (price currency)"
        lines.append(f"| {w.upper()} / {r['meta']['run_id']} | {calls} | {pin/calls:.2f} / {pout/calls:.2f} | {pin/units:.2f} / {pout/units:.2f} ({units} {'turns' if w == 'w1' else 'answers'}) | {cost} |")
    lines += ["", "W2 totals cover all model purposes, including calls ending in fallback; dividing by answer routes is an amortized answer cost, not isolated answer-generation tokens. Shared prices are a scenario only: W1 and W2 use different models, so supply each model's day-of price separately for a billed estimate.", "", "## Misses and incidents", "", "W2 run history (values read from saved JSON):"]
    for p, r in runs:
        if p.name.startswith("w2-"):
            m = r["metrics"]
            lines.append(f"- [evals/runs/{p.name}](runs/{p.name}): content_hit={m.get('content_hit', 'not measured')}; verified_rate={m.get('verified_rate', 'not measured')}.")
    lines += ["", "The mg/dL verifier fix stopped lab units being mistaken for doses: `services/records/tests/test_w2.py::test_lab_value_in_mg_per_dl_passes_verification` and `services/agent/tests/test_guards_lab_units.py`. See [W2 pod findings](../AI-COLLABORATION.md).", "", "The [2026-11-02 triage-retry incident](../docs/api-controls.md#incident-2026-11-02) documents the duplicate POST/null-thread failure and concurrent replay regressions.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs-dir", type=Path, default=ROOT / "evals/runs")
    parser.add_argument("--output", type=Path, default=ROOT / "evals/report.md")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build_report(args.runs_dir), encoding="utf-8")


if __name__ == "__main__":
    main()
