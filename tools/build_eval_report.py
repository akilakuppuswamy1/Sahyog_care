"""Build an evidence report from saved runs only; never executes an evaluation."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from evals.judge import JUDGE_PROMPT_VERSION, faithfulness_status

ROOT = Path(__file__).resolve().parents[1]


def build_report(runs_dir: Path) -> str:
    runs = [(p, json.loads(p.read_text(encoding="utf-8"))) for p in sorted(runs_dir.glob("*.json"))]
    ingest_benchmarks = sorted(runs_dir.glob("ingest-bench-*.json"))
    load_runs = [(p, r) for p, r in runs if p.name.startswith("load-")]
    latest = {}
    calibrations = [r for p, r in runs if p.name.startswith("judge-calibration-")]
    for p, run in sorted(runs, key=lambda pair: (pair[1].get("meta", {}).get("run_id", pair[0].stem), pair[0].name)):
        workflow = p.name.split("-")[0]
        if workflow in ("w1", "w2", "w3") and run.get("meta", {}).get("mode") != "rules":
            latest[workflow] = (p, run)

    def availability(metrics):
        measured = metrics.get("availability")
        if measured is not None:
            return measured
        degraded = metrics.get("degraded_rate")
        return round(1 - degraded, 3) if degraded is not None else "not measured"

    def judge_review(run_id):
        review_path = runs_dir / f"judge-review-w2-{run_id}.md"
        if not review_path.exists():
            review_path = runs_dir / f"judge-review-{run_id}.md"
        if not review_path.exists():
            return None
        review = review_path.read_text(encoding="utf-8")
        match = re.search(r"^Human review:\s*(\d+)\s+real\s*/\s*(\d+)\s+judge errors\s*$",
                          review, flags=re.IGNORECASE | re.MULTILINE)
        if not match:
            raise ValueError(f"Malformed judge review summary: {review_path}")
        return (f"human review of judge-0 cases: {match.group(1)} real / "
                f"{match.group(2)} judge errors ({run_id})")

    lines = ["# Evaluation report", "", "Generated by `tools/build_eval_report.py` from saved JSON; no eval or model call.", "",
             "## Headline (latest graph runs)", "", "| Workflow | Run | Model | p95 (s) | Fallback rate | Metrics |",
             "|---|---|---|---|---|---|"]
    for workflow, (p, r) in sorted(latest.items()):
        m = r["metrics"]
        keys = (("red_flag_recall", "specialty_accuracy", "specialty_accuracy_when_answered",
                 "degraded_rate", "availability") if workflow == "w1" else
                ("content_hit", "verified_rate", "scope_leaks", "degraded_rate", "availability")
                if workflow == "w2" else
                ("field_f1_macro", "medicine_precision", "medicine_recall", "invented_molecules",
                 "class_only_handled", "stock_flag_correct"))
        values = {key: availability(m) if key == "availability" else m.get(key, "not measured") for key in keys}
        if workflow == "w2":
            keys = (*keys, "faithfulness")
            values["faithfulness"] = faithfulness_status(r, calibrations)
            review = judge_review(r["meta"]["run_id"])
            if review:
                values["faithfulness"] += f"; {review}"
        lines.append(f"| {workflow.upper()} | {r['meta']['run_id']} | {r['meta'].get('model', 'not recorded')} | "
                     f"{m.get('latency_p95_s', 'not measured')} | {m.get('fallback_rate', 'not measured')} | " +
                     "; ".join(f"{k}={values[k]}" for k in keys) + " |")
    lines += ["", "## Judge calibration provenance", "",
              f"Only the latest held-out run for current prompt `{JUDGE_PROMPT_VERSION}` with kappa >= 0.6 and matching judge model authorizes faithfulness.", "",
              "| Set | Run | Cases | Kappa | Judge prompt version |", "|---|---|---:|---:|---|"]
    for c in sorted(calibrations, key=lambda c: c.get("meta", {}).get("run_id", "")):
        cm = c.get("meta", {})
        kind = cm.get("calibration_set", "original" if cm.get("cases") == 30 else "unknown")
        lines.append(f"| {kind} | {cm.get('run_id', 'not recorded')} | {cm.get('cases', 'not recorded')} | "
                     f"{c.get('metrics', {}).get('kappa', 'not measured')} | {cm.get('judge_prompt_version', 'not recorded')} |")
    if not any(c.get("meta", {}).get("calibration_set") == "holdout" for c in calibrations):
        lines.append("| holdout | not measured | 20 | not measured | not measured |")
    for version in ("w2-faithfulness-v1", JUDGE_PROMPT_VERSION):
        if not any(c.get("meta", {}).get("judge_prompt_version") == version
                   and c.get("meta", {}).get("calibration_set", "original" if c.get("meta", {}).get("cases") == 30 else "unknown") == "original"
                   for c in calibrations):
            lines.append(f"| original | not measured | 30 | not measured | {version} |")
    lines += ["", "## Page 16 targets", "", "| Target | Measured (run id) | Met | Evidence | Gap / measurement tier and day |", "|---|---|---|---|---|"]

    def measured(label, workflow, key, predicate, subkey=None):
        pair = latest.get(workflow)
        value = pair[1]["metrics"].get(key) if pair else None
        if subkey is not None and value is not None:
            value = value.get(subkey)
        lines.append(f"| {label} | {value if value is not None else 'not measured'}" +
                     (f" ({pair[1]['meta']['run_id']})" if pair and value is not None else "") +
                     f" | {'yes' if value is not None and predicate(value) else 'NO'} | " +
                     (f"evals/runs/{pair[0].name}" if pair else "No saved run") +
                     " | Synthetic set only; not a production guarantee |")

    def gap(label, evidence, reason, status="NO"):
        lines.append(f"| {label} | not measured | {status} | {evidence} | {reason} |")

    measured("Triage turn p95 < 4 s", "w1", "latency_p95_s", lambda x: x < 4)
    measured("Record answer p95 < 8 s", "w2", "latency_p95_s", lambda x: x < 8)
    measured("W1 degraded rate <= 0.02", "w1", "degraded_rate", lambda x: x <= 0.02)
    measured("W2 degraded rate <= 0.02", "w2", "degraded_rate", lambda x: x <= 0.02)
    measured("Note draft p95 < 20 s", "w3", "latency_p95_s", lambda x: x < 20)
    for field in ("S", "O", "A", "P"):
        measured(f"W3 SOAP field F1 >= 0.9 ({field})", "w3", "field_f1",
                 lambda x: x >= .9, subkey=field)
    measured("W3 invented molecules = 0", "w3", "invented_molecules", lambda x: x == 0)
    review_pair = latest.get("w3")
    review_p95 = review_pair[1]["metrics"].get("review_time_p95_s") if review_pair else None
    if review_p95 is None:
        gap("W3 doctor review time p95 < 90 s",
            "services/api/ops.py: note_draft.review_started_at to clinical_note.signed_at",
            "No signed-note review timings in saved evals; the sourced ops tile appears after signing.")
    else:
        measured("W3 doctor review time p95 < 90 s", "w3", "review_time_p95_s", lambda x: x < 90)
    measured("Red-flag recall 100%", "w1", "red_flag_recall", lambda x: x == 1)
    measured("Specialty accuracy >= 85%", "w1", "specialty_accuracy", lambda x: x >= .85)
    w2 = latest.get("w2")
    status = faithfulness_status(w2[1], calibrations) if w2 else "not measured"
    if w2:
        review = judge_review(w2[1]["meta"]["run_id"])
        if review:
            status += f"; {review}"
    certified = status not in ("not measured",) and not status.startswith("judge not calibrated")
    lines.append(f"| Answer faithfulness >= 0.9, calibrated judge | {status} | "
                 f"{'yes' if certified and w2[1]['metrics']['judge_score'] >= .9 else 'NO'} | "
                 "Independent evidence judge; latest matching calibration required | Synthetic answers only |")
    measured("Scope leaks 0 on red-team set", "w2", "scope_leaks", lambda x: x == 0)
    gap("Bookings completed without a call >= 70% of synthetic sessions", "services/agent/tests/test_w1_graph.py::test_routine_case_pauses_for_the_pick_then_books_on_resume", "Triage runs stop before booking; Core demo/day-8 end-to-end session measurement pending")
    gap("Time to book median < 3 min", "Same booking test; no session timing run", "Core demo/day-8 timed synthetic sessions pending")
    gap("Availability 99.5% in clinic hours", "infra/docker-compose.yml", "Not measured; Architect clinic-hours observation day (unscheduled)")
    gap("Audit: every record read logged with actor, purpose, time", "services/records/tests/test_w2.py::test_answer_is_cited_verified_and_audited; infra/db/tests/test_schema.py::test_audit_is_append_only_and_answers_who_saw; services/agent/w2/tools.py; infra/db/001_schema.sql", "Core application read auditing exists; tests cover answer reads/actor and append-only schema, not exhaustive SQL read coverage. Architect access-path audit day (unscheduled)", "partial")
    gap("Cost per consultation computed with p.34 formula", "Saved run tokens; cost section below", "Measured call/turn token averages only; full consultation workflow mix and prices pending Core demo/day-8", "partial")
    gap("Residency: identified text stays in-region", "services/agent/w1/guards.py; infra/deployment-adr.md", "Regex egress guard exists; hosting region and complete de-identification unverified. Architect deployment day (unscheduled)", "partial")
    gap("Retention: audio gone within 24 h; audit kept 1 year", "infra/db/001_schema.sql", "Append-only audit exists; no timed retention proof. Pro W3 audio lifecycle; Architect audit retention validation day (unscheduled)")
    gap("Recovery: restore within 4 h", "infra/docker-compose.yml", "Not measured; Architect timed backup/restore drill day (unscheduled)")
    gap("Recovery: checkpoints survive restarts", "services/agent/w1/cli.py (--resume); services/agent/tests/test_w1_graph.py::test_resume_after_restart_uses_the_checkpoint; services/api/tests/test_api_postgres.py::test_postgres_pick_slot_resume_and_replay", "W1 Postgres resume path exists; graph test recompiles against shared saver, not a process crash. W2 lacks durable checkpointer. Architect crash drill day (unscheduled)", "partial")
    lines += ["", "## Degraded rate, availability and W1 specialty accuracy per saved run", "",
              "| Workflow | Run | Degraded rate | Availability | Specialty accuracy | Specialty accuracy when answered |",
              "|---|---|---:|---:|---:|---:|"]
    for p, r in runs:
        workflow = p.name.split("-")[0]
        m = r.get("metrics", {})
        specialty = m.get("specialty_accuracy", "not measured") if workflow == "w1" else "not measured"
        answered = m.get("specialty_accuracy_when_answered", "not measured") if workflow == "w1" else "not measured"
        lines.append(f"| {workflow.upper()} | {r.get('meta', {}).get('run_id', 'not recorded')} | "
                     f"{m.get('degraded_rate', 'not measured')} | {availability(m)} | {specialty} | {answered} |")
    lines += ["", "## p95 spread across graph runs", "",
              "| Workflow | Runs | Minimum p95 (s) | Maximum p95 (s) | Spread (s) |",
              "|---|---:|---:|---:|---:|"]
    for workflow in ("w1", "w2", "w3"):
        values = [r.get("metrics", {}).get("latency_p95_s") for p, r in runs
                  if p.name.startswith(f"{workflow}-") and r.get("meta", {}).get("mode") != "rules" and
                  isinstance(r.get("metrics", {}).get("latency_p95_s"), (int, float))]
        if values:
            low, high = min(values), max(values)
            lines.append(f"| {workflow.upper()} | {len(values)} | {low} | {high} | {round(high - low, 2)} |")
        else:
            lines.append(f"| {workflow.upper()} | 0 | not measured | not measured | not measured |")
    lines += ["", "## Every saved run (variance)", "",
              "| File | Run id | Model | Prompt / rules version | p95 (s) | Fallback rate |",
              "|---|---|---|---|---:|---:|"]
    for p, r in runs:
        meta, m = r.get("meta", {}), r.get("metrics", {})
        lines.append(f"| evals/runs/{p.name} | {meta.get('run_id', 'not recorded')} | {meta.get('model', 'not recorded')} | "
                     f"{meta.get('prompt_version', 'not recorded')} / {meta.get('rules_version', 'not recorded')} | "
                     f"{m.get('latency_p95_s', 'not measured')} | {m.get('fallback_rate', 'not measured')} |")
    lines += ["", "## Cost worksheet (p.34)", "",
              "See the generated [cost worksheet](../docs/cost-sheet.md) for measured saved-run token totals, "
              "workflow-specific price formulas, the consultation-cost scenario and documented gaps. "
              "Generate it with `python tools/build_cost_sheet.py`; no evaluation is run.", "",
              "## Latest load test", ""]
    if load_runs:
        load_path, load_run = max(
            load_runs,
            key=lambda pair: (pair[1].get("meta", {}).get("run_id", pair[0].stem), pair[0].name),
        )
        meta = load_run.get("meta", {})
        summary = load_run.get("summary", {})
        model_latency = meta.get("model_latency", {})
        lines += [
            f"Saved run: [evals/runs/{load_path.name}](runs/{load_path.name}) — "
            f"run id `{meta.get('run_id', load_path.stem)}`; "
            f"**{load_run.get('status', 'not recorded')}**; "
            f"{summary.get('requests', 'not recorded')} requests; "
            f"{summary.get('requests_per_second', 'not measured')} RPS; "
            f"error rate {summary.get('error_rate', 'not measured')}; "
            f"429 rate {summary.get('rate_429', 'not measured')}; "
            f"{len(meta.get('observed_replicas', []))}/{meta.get('configured_replicas', 'not recorded')} "
            "replicas observed.",
            "",
            (("Model latency is stubbed for this run. Provenance: "
              f"`{json.dumps(model_latency, sort_keys=True)}`.")
             if model_latency else
             "Live model calls were explicitly permitted for this run."),
            "",
            "| Workflow | p95 (ms) | Target (ms) | Result |",
            "|---|---:|---:|---|",
        ]
        for workflow, values in sorted(load_run.get("workflows", {}).items()):
            lines.append(f"| {workflow.upper()} | {values.get('p95_ms', 'not measured')} | "
                         f"{values.get('target_ms', 'not recorded')} | "
                         f"{'PASS' if values.get('pass') else 'FAIL'} |")
        lines += ["", "### Per-endpoint p95", "",
                  "| Endpoint | RPS | p95 (ms) | Target (ms) | Result |",
                  "|---|---:|---:|---:|---|"]
        for endpoint, values in sorted(load_run.get("routes", {}).items()):
            lines.append(f"| {endpoint} | {values.get('rps', 'not measured')} | "
                         f"{values.get('p95_ms', 'not measured')} | "
                         f"{values.get('target_ms', 'not recorded')} | "
                         f"{'PASS' if values.get('pass') else 'FAIL'} |")
    else:
        lines.append("Not measured; run `python tools/load_test.py` against the scale profile to create a saved load run.")
    lines += ["", "## Latest ingest benchmark", ""]
    if ingest_benchmarks:
        benchmark_path = ingest_benchmarks[-1]
        benchmark = json.loads(benchmark_path.read_text(encoding="utf-8"))
        sequential = benchmark["sequential"]
        parallel = benchmark["parallel"]
        lines += [f"Saved offline benchmark: [evals/runs/{benchmark_path.name}](runs/{benchmark_path.name}) "
                  f"({benchmark.get('meta', {}).get('documents', 'not recorded')} synthetic documents).", "",
                  "| Mode | Docs/s | p95 per document (s) | Peak concurrency | Failures |",
                  "|---|---:|---:|---:|---:|"]
        for label, metrics in (("Sequential", sequential), ("Parallel", parallel)):
            lines.append(f"| {label} | {metrics.get('docs_per_second', 'not measured')} | "
                         f"{metrics.get('p95_per_document_seconds', 'not measured')} | "
                         f"{metrics.get('peak_concurrency', 'not measured')} | "
                         f"{metrics.get('failed_documents', 'not measured')} |")
    else:
        lines.append("Not measured; run `python tools/bench_ingest.py` to create a saved offline benchmark.")
    lines += ["", "## Misses and incidents", "", "W2 run history (values read from saved JSON):"]
    for p, r in runs:
        if p.name.startswith("w2-"):
            m = r["metrics"]
            lines.append(f"- [evals/runs/{p.name}](runs/{p.name}): content_hit={m.get('content_hit', 'not measured')}; verified_rate={m.get('verified_rate', 'not measured')}.")
    lines += ["", "The mg/dL verifier fix stopped lab units being mistaken for doses: `services/records/tests/test_w2.py::test_lab_value_in_mg_per_dl_passes_verification` and `services/agent/tests/test_guards_lab_units.py`. See [W2 pod findings](../AI-COLLABORATION.md).", "", "The [2026-11-02 triage-retry incident](../docs/api-controls.md#incident-2026-11-02) documents the duplicate POST/null-thread failure and concurrent replay regressions.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs-dir", type=Path, default=ROOT / "evals/runs")
    parser.add_argument("--output", type=Path, default=ROOT / "evals/report.md")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build_report(args.runs_dir), encoding="utf-8")


if __name__ == "__main__":
    main()
